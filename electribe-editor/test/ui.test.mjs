import { chromium } from "playwright";
import { spawn } from "node:child_process";
import fs from "node:fs";
import assert from "node:assert/strict";
const srv = spawn("python3", ["-m", "http.server", "8123", "-d", new URL("..", import.meta.url).pathname], { stdio: "ignore" });
await new Promise(r => setTimeout(r, 800));
const mk = (n) => { const b = Buffer.alloc(512, 0); b.write("KICK01  ", 0x40); b[0x100] = 5; return b; };
fs.writeFileSync("/tmp/t.esx", mk()); const b2 = mk(); b2[0x123] = 77; fs.writeFileSync("/tmp/t2.esx", b2);
const br = await chromium.launch({ executablePath: process.env.CHROME || "/opt/pw-browsers/chromium" }).catch(() => chromium.launch());
const pg = await br.newPage(); const errs = []; pg.on("pageerror", e => errs.push(e.message));
await pg.goto("http://localhost:8123/index.html");
await pg.setInputFiles("#file", "/tmp/t.esx");
assert.equal(await pg.textContent("#kind"), "ESX-1");
await pg.click('[data-k=scan]');
await pg.fill(".nm >> nth=0", "SNARE02"); await pg.dispatchEvent(".nm >> nth=0", "change");
await pg.click('[data-add]');
await pg.click('[data-k=params]');
assert.equal(await pg.inputValue('#fields input'), "SNARE02");
await pg.click('[data-k=hex]'); await pg.fill('#hexoff','256'); await pg.click('#hexgo'); await pg.fill('input[data-o="256"]', "ff"); await pg.dispatchEvent('input[data-o="256"]', "change");
await pg.click('[data-k=diff]'); await pg.setInputFiles("#after", "/tmp/t2.esx");
assert.match(await pg.textContent("#diffout"), /1 Byte/);
await pg.click("#addDiff");
await pg.click('[data-k=params]');
assert.equal(await pg.locator("#fields input").count(), 2);
const [dl] = await Promise.all([pg.waitForEvent("download"), pg.click('[data-k=file]').then(() => pg.click("#save"))]);
await dl.saveAs("/tmp/out.esx"); const o = fs.readFileSync("/tmp/out.esx");
assert.equal(o.toString("latin1", 0x40, 0x47), "SNARE02"); assert.equal(o[0x100], 0xff);
await pg.click('[data-k=sysex]'); await pg.fill("#sxin", "80 ff 12"); await pg.click("#p7");
assert.equal(await pg.textContent("#sxout"), "03 00 7f 12");
assert.deepEqual(errs, []);
console.log("UI ok"); await br.close(); srv.kill();
